import { useEffect, useState } from 'react';
import { Search, Download, ExternalLink, Trash2, Printer, FolderArchive } from 'lucide-react';
import { apiRequest, downloadFile } from '../api/client';
import { useAuth } from '../context/AuthContext';
import { formatBytes, formatDateTime } from '../utils/format';

const DOC_TYPES = [
  'Audit Report',
  'Financial Summary',
  'Excel Export',
  'Supporting Document',
  'Database Backup',
];

export function DocumentCenterPage() {
  const { hasRole } = useAuth();
  const isAdmin = hasRole('admin');
  const [docs, setDocs] = useState<any[]>([]);
  const [search, setSearch] = useState('');
  const [docType, setDocType] = useState('');
  const [loading, setLoading] = useState(true);

  const loadDocs = async () => {
    setLoading(true);
    try {
      const qs = new URLSearchParams({ search, doc_type: docType });
      const res = await apiRequest(`/api/documents?${qs.toString()}`);
      setDocs(res.documents || []);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    loadDocs();
  }, [search, docType]);

  const handleDelete = async (doc: any) => {
    if (!window.confirm(`Permanently delete "${doc.title}" from the Document Center?`)) return;
    try {
      await apiRequest(`/api/documents/${doc.id}`, { method: 'DELETE' });
      await loadDocs();
    } catch (err: any) {
      alert(err.message);
    }
  };

  return (
    <div className="space-y-5">
      <div className="flex flex-col sm:flex-row sm:items-center sm:justify-between gap-2">
        <div>
          <h1 className="text-xl font-bold text-slate-900">Centralized Document Center</h1>
          <p className="text-xs text-slate-500">
            Organized repository of all generated PDFs, Excel workbooks, CV exports, and supporting documents
          </p>
        </div>
        <button
          type="button"
          onClick={() => window.print()}
          className="inline-flex items-center gap-1.5 px-3 py-1.5 text-xs font-medium bg-white border border-slate-300 rounded-md hover:bg-slate-50 no-print"
        >
          <Printer className="w-3.5 h-3.5" />
          Print Index
        </button>
      </div>

      <div className="bg-white p-4 rounded-xl border border-slate-200/80 shadow-sm grid grid-cols-1 sm:grid-cols-3 gap-3 no-print">
        <div className="relative sm:col-span-2">
          <Search className="w-4 h-4 text-slate-400 absolute left-3 top-2.5" />
          <input
            type="text"
            value={search}
            onChange={(e) => setSearch(e.target.value)}
            placeholder="Search by document title, reference no., or author..."
            className="w-full pl-9 pr-3 py-1.5 text-xs border border-slate-300 rounded-md"
          />
        </div>
        <select
          value={docType}
          onChange={(e) => setDocType(e.target.value)}
          className="px-3 py-1.5 text-xs border border-slate-300 rounded-md bg-white"
        >
          <option value="">All Document Types</option>
          {DOC_TYPES.map((t) => (
            <option key={t} value={t}>
              {t}
            </option>
          ))}
        </select>
      </div>

      <div className="bg-white rounded-xl border border-slate-200/80 shadow-sm overflow-hidden">
        <div className="overflow-x-auto">
          <table className="w-full text-xs">
            <thead className="bg-slate-50 border-b border-slate-200 text-slate-600">
              <tr>
                <th className="px-3 py-2.5 text-left font-semibold">Document Title</th>
                <th className="px-3 py-2.5 text-left font-semibold">Type</th>
                <th className="px-3 py-2.5 text-left font-semibold">Reference</th>
                <th className="px-3 py-2.5 text-right font-semibold">Size</th>
                <th className="px-3 py-2.5 text-left font-semibold">Generated By</th>
                <th className="px-3 py-2.5 text-left font-semibold">Created</th>
                <th className="px-3 py-2.5 text-right font-semibold no-print">Actions</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-100">
              {loading ? (
                <tr>
                  <td colSpan={7} className="px-4 py-8 text-center text-slate-500">
                    Loading documents...
                  </td>
                </tr>
              ) : docs.length === 0 ? (
                <tr>
                  <td colSpan={7} className="px-4 py-10 text-center text-slate-500">
                    <FolderArchive className="w-6 h-6 text-slate-300 mx-auto mb-2" />
                    No documents archived yet. Export a report, CV, or upload supporting documents to populate this center.
                  </td>
                </tr>
              ) : (
                docs.map((doc) => (
                  <tr key={doc.id} className="hover:bg-slate-50/70">
                    <td className="px-3 py-2.5 font-medium text-slate-900">{doc.title}</td>
                    <td className="px-3 py-2.5">
                      <span className="px-2 py-0.5 text-[11px] bg-slate-100 text-slate-700 rounded border border-slate-200">
                        {doc.doc_type}
                      </span>
                    </td>
                    <td className="px-3 py-2.5 font-mono text-[11px] text-slate-600">{doc.reference_no || '-'}</td>
                    <td className="px-3 py-2.5 text-right tabular-nums text-slate-600">{formatBytes(doc.file_size)}</td>
                    <td className="px-3 py-2.5 text-slate-700">{doc.generated_by_name}</td>
                    <td className="px-3 py-2.5 text-slate-500 tabular-nums whitespace-nowrap">
                      {formatDateTime(doc.created_at)}
                    </td>
                    <td className="px-3 py-2.5 text-right whitespace-nowrap no-print">
                      <div className="inline-flex items-center gap-1">
                        <a
                          href={doc.file_path}
                          target="_blank"
                          rel="noreferrer"
                          className="p-1.5 text-slate-500 hover:text-navy-700 hover:bg-slate-100 rounded"
                          title="Open / View"
                        >
                          <ExternalLink className="w-3.5 h-3.5" />
                        </a>
                        <button
                          type="button"
                          onClick={() => downloadFile(`/api/documents/${doc.id}/download`, doc.file_name)}
                          className="p-1.5 text-slate-500 hover:text-emerald-700 hover:bg-emerald-50 rounded"
                          title="Download"
                        >
                          <Download className="w-3.5 h-3.5" />
                        </button>
                        {isAdmin && (
                          <button
                            type="button"
                            onClick={() => handleDelete(doc)}
                            className="p-1.5 text-slate-400 hover:text-red-700 hover:bg-red-50 rounded"
                            title="Delete"
                          >
                            <Trash2 className="w-3.5 h-3.5" />
                          </button>
                        )}
                      </div>
                    </td>
                  </tr>
                ))
              )}
            </tbody>
          </table>
        </div>
      </div>
    </div>
  );
}
